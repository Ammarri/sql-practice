--потрібно перевірити якість даних у клієнтській базі: скільки клієнтів загалом, і яка частка з них не має заповненого номера телефону (у відсотках)
USE Northwind;
GO
SELECT
	COUNT(*) AS [Загальна кількість клієнтів],
	CAST(100.0 * (COUNT(*) - COUNT(Phone)) / COUNT(*) AS decimal(10,2)) AS [% без телефона]
FROM Customers;