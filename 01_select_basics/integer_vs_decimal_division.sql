--Запусти і поясни чому результати ділення відрізняються: 7/2 та 7.0/2
SELECT 
7/2 AS result_a,
7.0/2 AS result_b

--7/2 дає результат 3, тому що ділимо цілі числа, залишки відкидаються. Щоб отримати точний результат і не втратити інформацію, ми повинні у запиті одне з чисел прописати у вигляді десяткового дробу: 7.0 або 2.0
